// Generates supabase/seed.sql from the markdown teams in src/content/teams.
// Run: npm run seed:sql   (safe to re-run the SQL: teams are upserted by slug)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/content/teams');
const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

const rows = readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((file) => {
    const text = readFileSync(join(dir, file), 'utf8');
    const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
    const data = {};
    for (const line of (m?.[1] ?? '').split('\n')) {
      const kv = line.match(/^(\w+):\s*(.*)$/);
      if (kv) data[kv[1]] = kv[2].replace(/^["']|["']$/g, '');
    }
    const name = data.teamName;
    const gender = /girls/i.test(name) ? 'Girls' : 'Mixed';
    const age = Number.parseInt(String(data.ageGroup).replace(/\D/g, ''), 10) || 99;
    return { slug: file.replace(/\.md$/, ''), name, age, ageGroup: data.ageGroup, gender, ...data, body: (m?.[2] ?? '').trim() };
  });

rows.sort((a, b) => a.age - b.age || a.name.localeCompare(b.name));

const values = rows
  .map(
    (t, i) =>
      `  (${q(t.slug)}, ${q(t.name)}, ${q(t.ageGroup)}, ${q(t.gender)}, ${q(t.matchday)}, ${q(t.league)}, ${q(t.season)}, ${q(t.training)}, null, ${(i + 1) * 10})`
  )
  .join(',\n');

const coaches = rows
  .filter((t) => t.coach)
  .map((t) => `  (${q(t.slug)}, ${q(t.coach)})`)
  .join(',\n');

const sql = `-- Generated by scripts/generate-seed-sql.mjs from src/content/teams. Do not edit by hand.
-- Safe to re-run: teams are matched by slug and only the club's starting
-- details are refreshed, so run it once, then manage teams in the portal.
insert into public.teams (slug, name, age_group, gender, match_day, league, season, training, description, sort_order)
values
${values}
on conflict (slug) do nothing;

-- Coach names from the markdown files become each team's contact name, but
-- only where a manager hasn't already set one. (Needs migration 002.)
update public.teams t
set contact_name = c.coach
from (values
${coaches}
) as c(slug, coach)
where t.slug = c.slug and t.contact_name is null;
`;
writeFileSync(join(root, 'supabase/seed.sql'), sql);
console.log(`Wrote supabase/seed.sql with ${rows.length} teams`);
