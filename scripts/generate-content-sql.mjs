// Generates supabase/seed-content.sql from the markdown pages and blog posts in
// src/content, so they can be edited in the portal. Run: npm run content:sql
// The SQL only inserts rows that don't exist yet: it never overwrites edits
// made in the portal, so it's safe to re-run.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Minimal front-matter reader for this site's files (scalars and simple lists). */
function parse(file) {
  const text = readFileSync(file, 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  const data = {};
  let listKey = null;
  for (const line of (m?.[1] ?? '').split('\n')) {
    const item = line.match(/^\s+-\s+(.*)$/);
    if (item && listKey) {
      data[listKey].push(unquote(item[1]));
      continue;
    }
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    if (kv[2] === '') {
      listKey = kv[1];
      data[listKey] = [];
    } else {
      listKey = null;
      data[kv[1]] = unquote(kv[2]);
    }
  }
  const body = (m?.[2] ?? text).replace(/^\n+/, '').replace(/\s+$/, '') + '\n';
  return { data, body };
}

function unquote(v) {
  const s = v.trim();
  const quoted = (s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"));
  return quoted ? s.slice(1, -1).replace(/\\"/g, '"') : s;
}

const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const bool = (v) => (v === true || v === 'true' ? 'true' : 'false');

/** Dollar-quoted string literal, so markdown and HTML go in untouched. */
function dollar(v) {
  const DOLLAR = String.fromCharCode(36);
  let tag = 'md';
  while (v.includes(DOLLAR + tag + DOLLAR)) tag += 'x';
  const fence = DOLLAR + tag + DOLLAR;
  return fence + v + fence;
}

const pagesDir = join(root, 'src/content/pages');
const pages = readdirSync(pagesDir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => {
    const { data, body } = parse(join(pagesDir, f));
    const slug = f.replace(/\.md$/, '');
    return [
      'insert into public.site_pages (slug, title, description, body, nav_label, show_in_nav, sort_order, seo_title, seo_description, noindex)',
      `values (${q(slug)}, ${q(data.title)}, ${q(data.description ?? '')}, ${dollar(body)}, ${q(data.navLabel)}, ${bool(data.showInNav)}, ${Number(data.order) || 100}, ${q(data.seoTitle)}, ${q(data.seoDescription)}, ${bool(data.noindex)})`,
      'on conflict (slug) do nothing;'
    ].join('\n');
  });

const blogDir = join(root, 'src/content/blog');
const posts = readdirSync(blogDir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => {
    const { data, body } = parse(join(blogDir, f));
    const slug = f.replace(/\.md$/, '');
    const tags = (data.tags ?? []).map((t) => q(t)).join(', ');
    return [
      'insert into public.posts (slug, title, date, excerpt, body, cover_image, tags, author, draft, seo_title, seo_description)',
      `values (${q(slug)}, ${q(data.title)}, ${q(data.date)}, ${q(data.excerpt ?? '')}, ${dollar(body)}, ${q(data.coverImage)}, array[${tags}]::text[], ${q(data.author ?? 'Fusion Football Club')}, ${bool(data.draft)}, ${q(data.seoTitle)}, ${q(data.seoDescription)})`,
      'on conflict (slug) do nothing;'
    ].join('\n');
  });

const sql = `-- Generated by scripts/generate-content-sql.mjs from src/content. Do not edit by hand.
-- Copies the site's pages and blog posts into the database so club admins can
-- edit them in the portal. Needs migration 004. Safe to re-run: rows that
-- already exist (including anything edited in the portal) are left alone.

${pages.join('\n\n')}

${posts.join('\n\n')}
`;
writeFileSync(join(root, 'supabase/seed-content.sql'), sql);
console.log(`Wrote supabase/seed-content.sql: ${pages.length} pages, ${posts.length} posts`);
